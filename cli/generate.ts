/**
 * Generates strategies with LLMs, one model after another (same loop as the app's Model Lab: prompt → extract →
 * smoke test → repair). Writes strategies/<label>.js and strategies/<label>.gen.json.
 *
 *   npm run generate -- --base-url http://host:11434/v1 --api-key-env LLAMA_SWAP_API_KEY --model qwen3.8-coder --model other
 *   npm run generate -- --kind claude-code --effort medium --model claude-sonnet-5-5   (uses your Claude subscription)
 *
 * --tag NAME              file names become <model>@<NAME>-s<k> (e.g. claude-opus-5@max-s1)
 * --samples N             N independent generations per model (measures how much a model varies between attempts)
 * --improve-from FILE     improvement round: for each model, take its best-rated strategy in that results file
 *                         (from `npm run bench`), send the code plus its own tournament numbers, ask for a better one
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { Agent, setGlobalDispatcher } from 'undici';
import { tournamentSummary } from '../src/bench/summary';
import { validateStrategy } from '../src/bench/validate';
import { claudeCodeChat } from '../src/llm/claudeCode';
import { generateStrategy } from '../src/llm/generate';
import type { ProviderConfig, ProviderKind } from '../src/llm/providers';
import { DEFAULT_RULESET } from '../src/sim/ruleset';

// Local models can think for many minutes before the first byte; Node's default 5-minute header timeout is too short.
setGlobalDispatcher(new Agent({ headersTimeout: 0, bodyTimeout: 0 }));

const args = process.argv.slice(2);
const opt = (name: string, def?: string) => {
  const i = args.indexOf(name);
  return i >= 0 && i + 1 < args.length ? args[i + 1] : def;
};
const models = args.flatMap((a, i) => (a === '--model' ? [args[i + 1]] : []));
const kind = opt('--kind', 'openai') as ProviderKind;
const baseUrl = opt('--base-url', kind === 'claude-code' ? 'claude-code-cli' : undefined);
if (!baseUrl || !models.length) {
  console.log('usage: npm run generate -- --base-url URL [--kind openai|anthropic|claude-code] [--api-key-env NAME] --model ID [--model ID…]\n  [--temperature 0.2] [--max-tokens 32000] [--effort medium] [--max-repairs 3] [--out-dir strategies]');
  process.exit(1);
}
const keyEnv = opt('--api-key-env');
const provider: ProviderConfig = {
  id: 'cli',
  name: 'cli',
  kind,
  baseUrl,
  apiKey: keyEnv ? (process.env[keyEnv] ?? '') : '',
  useProxy: false,
};
if (keyEnv && !provider.apiKey) throw new Error(`environment variable ${keyEnv} is empty`);
const outDir = opt('--out-dir', 'strategies')!;
mkdirSync(outDir, { recursive: true });
const effort = opt('--effort');
const params =
  kind === 'claude-code'
    ? { temperature: null, maxTokens: 0, effort: effort ?? 'medium' }
    : { temperature: Number(opt('--temperature', '0.2')), maxTokens: Number(opt('--max-tokens', '32000')), ...(effort ? { effort } : {}) };
const maxRepairs = Number(opt('--max-repairs', '3'));
const samples = Math.max(1, Number(opt('--samples', '1')));

/** Improvement round: the best strategy of `model` in a results file, and the summary to send back. */
function improveInput(model: string): { code: string; summary: string; parent: string } | undefined {
  const file = opt('--improve-from');
  if (!file) return undefined;
  const res = JSON.parse(readFileSync(file, 'utf8'));
  const modelOf = (id: string) => {
    const g = join(outDir, `${id}.gen.json`);
    return existsSync(g) ? JSON.parse(readFileSync(g, 'utf8')).model : null;
  };
  const row = res.leaderboard.rows.find((r: { strategy: string }) => modelOf(r.strategy) === model);
  if (!row) throw new Error(`${file} has no strategy generated by ${model}`);
  const summary = tournamentSummary({ config: res.tournament, leaderboard: res.leaderboard, matches: res.matches, name: (id) => id }, row.strategy);
  return { code: readFileSync(join(outDir, `${row.strategy}.js`), 'utf8'), summary, parent: row.strategy };
}

for (const model of models.flatMap((m) => Array.from({ length: samples }, () => m))) {
  const t0 = Date.now();
  const improve = improveInput(model);
  console.log(`\n╭─ ${model}${improve ? ` · improving ${improve.parent}` : ''}`);
  const rec = await generateStrategy({
    improve: improve ? { code: improve.code, summary: improve.summary } : undefined,
    provider,
    model,
    rules: DEFAULT_RULESET,
    params,
    maxRepairs,
    validate: async (code) => validateStrategy(code, DEFAULT_RULESET),
    ...(kind === 'claude-code'
      ? {
          chatFn: claudeCodeChat({ model, effort: params.effort ?? 'medium' }),
          providerNote: `Claude Code CLI, --effort ${params.effort}; temperature and max output tokens are the CLI defaults (not settable)`,
        }
      : {}),
    onEvent: (e) => {
      const at = `${((Date.now() - t0) / 1000).toFixed(0)}s`;
      if (e.type === 'request') console.log(`│ ${at} ❯ attempt ${e.attempt + 1}`);
      if (e.type === 'response') console.log(`│ ${at} ← ${e.text.length} chars in ${(e.latencyMs / 1000).toFixed(1)} s`);
      if (e.type === 'validation') console.log(`│ ${at} ${e.report.ok ? '✓' : '✗'} ${e.report.text.split('\n').slice(0, 3).join(' | ')}`);
      if (e.type === 'error') console.log(`│ ${at} ✗ ${e.message}`);
    },
  });
  const tag = opt('--tag');
  let name = tag ? `${model}@${tag}-s1` : model;
  const taken = (n: string) => ['.js', '.failed.js', '.gen.json'].some((ext) => existsSync(join(outDir, `${n}${ext}`)));
  for (let v = 2; taken(name); v++) name = tag ? `${model}@${tag}-s${v}` : `${model}-v${v}`;
  if (rec.code) writeFileSync(join(outDir, `${name}${rec.ok ? '' : '.failed'}.js`), rec.code);
  // Records may be published: keep the provider's host out unless it is a public API.
  const host = new URL(baseUrl.startsWith('http') ? baseUrl : 'http://local').hostname;
  const publicApi = /(^|\.)(openrouter\.ai|openai\.com|anthropic\.com)$/.test(host);
  const saved = { ...rec, provider: { ...rec.provider, baseUrl: publicApi || kind === 'claude-code' ? rec.provider.baseUrl : 'local-openai-compatible' } };
  writeFileSync(join(outDir, `${name}.gen.json`), JSON.stringify(improve ? { ...saved, parent: improve.parent } : saved, null, 1));
  console.log(
    `╰─ ${rec.ok ? '✓' : '✗'} ${name}: ${rec.repairs} repair(s), ${rec.inputTokens}+${rec.outputTokens} tokens, ${(rec.latencyMs / 1000).toFixed(0)} s${rec.error ? ` — ${rec.error}` : ''}`,
  );
}
